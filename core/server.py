    def upsert_connection(self, name, ctype, base_url, api_key):
        existing = self.find_connection(name)
        if existing is None:
            conn = {"name": name, "type": ctype, "baseUrl": base_url, "apiKey": None}
            self.data["connections"].append(conn)
        else:
            conn = existing
            conn["type"] = ctype
            conn["baseUrl"] = base_url
