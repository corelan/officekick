def filter_web_models(store, conn_name):
    """Models that plausibly support web search on this connection."""
    conn = store.find_connection(conn_name)
    if conn is None:
        raise ApiError(404, "Unknown connection: %r" % (conn_name,))
    t = conn["type"]
    try:
        resp = provider_list_models(store, conn_name)
        ids = [str(x) for x in (resp.get("models") or [])]
    except Exception:
        ids = []
    if t == "openrouter":
        # :online attaches to any model - everything is web-capable
        return ids
    if t == "ollama":
        # no native web search channel in Ollama itself
        return []
    def _webish(mid):
        ml = str(mid).lower()
        return any(h in ml for h in WEB_MODEL_NAME_HINTS)
    return [x for x in ids if _webish(x)]


def validate_search_steps(store, steps):
    """Validate an ordered lookup sequence: server engines or online lookups."""
    clean = []
    for st in (steps or [])[:6]:
        if not isinstance(st, dict):
            continue
        kind = str(st.get("kind") or "")
        if kind == "server":
            eng = str(st.get("engine") or "")
            if eng not in ("duckduckgo", "brave", "tavily", "firecrawl"):
                raise ApiError(400, "unknown search engine: %r" % (eng,))
            clean.append({"kind": "server", "engine": eng})
        elif kind == "online":
            conn = str(st.get("connection") or "")
            if not store.find_connection(conn):
                raise ApiError(400, "Lookup step references unknown connection: %r" % (conn,))
            model = str(st.get("model") or "").strip()
            step = {"kind": "online", "connection": conn}
            if model:
                step["model"] = model[:160]
            clean.append(step)
        else:
            raise ApiError(400, "search step kind must be server|online")
    return clean


IMAGE_MODEL_NAME_HINTS = (
    "image", "imagen", "seedream", "dall", "flux", "banana", "recraft",
    "ideogram", "kolors", "stable-diffusion", "sdxl", "sd3", "playground",
)


def _image_model_suggestion(requested, capable_ids):
    """Closest image-capable ids for a non-image model id (openrouter preflight)."""
    ids = [str(x) for x in capable_ids]
    cand = requested + "-image"
    if cand in ids:
        return [cand]
    low = requested.lower()
    near = sorted(
        {i for i in ids if i.lower().startswith(low) or low.startswith(i.lower())},
        key=len)[:3]
    return near or ids[:5]


def _model_is_image_capable(entry):
    """True for text->image models; prefers provider metadata (openrouter's
    architecture.output_modalities), falls back to id heuristics."""
    if not isinstance(entry, dict):
        return False
    ident = str(entry.get("id") or entry.get("name") or "")
    arch = entry.get("architecture") or {}
    outs = arch.get("output_modalities") or []
    if outs:
        return "image" in [str(x).lower() for x in outs]
    return any(h in ident.lower() for h in IMAGE_MODEL_NAME_HINTS)


def _parse_openai_models_raw(data):
    """OpenAI-style /models entries kept whole (metadata needed for filtering)."""
    if isinstance(data, dict) and isinstance(data.get("data"), list):
        return [m for m in data["data"] if isinstance(m, dict) and m.get("id")]
    if isinstance(data, list):
        return [m for m in data if isinstance(m, dict) and m.get("id")]
    return []


def _parse_openai_models(data):
    return [str(m["id"]) for m in _parse_openai_models_raw(data)]


def _dedupe(seq):
    seen = set()
    out = []
    for item in seq:
        if item and item not in seen:
            seen.add(item)
            out.append(item)
    return out


