def update_flag_path(store):
    return os.path.join(os.path.dirname(str(store.path)), "update.lock")


def installer_pid_alive(pid):
    """True while the spawned installer process still exists (0.9.314). The
    update lock is only MEANINGFUL while that process runs - once it exits
    (success or failure) the lock is stale and must not block the next
    update click."""
    try:
        pid = int(pid)
    except (TypeError, ValueError):
        return False
    if pid <= 0:
        return False
    if os.name == "nt":
        try:
            p = subprocess.run(["tasklist", "/FI", "PID eq %d" % pid],
                               stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                               timeout=10)
            return (str(pid) in (p.stdout or b"").decode("utf-8", "replace"))
        except Exception:
            return False
    if hasattr(os, "waitpid"):
        # POSIX: the installer is OUR child - waitpid(WNOHANG) reaps a dead
        # one (kill(0) alone reports zombies as alive) and reports (0, 0)
        # while it still runs.
        try:
            done = os.waitpid(pid, os.WNOHANG)
            return done[0] == 0   # (0, 0) = still running
        except ChildProcessError:
            pass   # not our child (or already reaped) - fall through
        except OSError:
            pass
    try:
        os.kill(pid, 0)   # signal 0: existence probe only
        return True
    except OSError:
        return False
    except Exception:
        return False


def spawn_installer_update(store):
    """POST /api/update-run: run install.py --update from the recorded clone
    as a DETACHED process - pull + redeploy + restart in one click (field:
    the pane's pull-only button left users on the old build; the deploy +
    restart always needed a second command). The installer STOPS this server
    mid-run (that is how it frees the port and starts the new build) - the
    pane polls /api/health until the generation changes. The 10-minute lock
    holds only while the spawned installer PROCESS is alive (0.9.314: the
    lock carries its PID; a dead installer = a stale lock that must not
    block the next click - field: a COMPLETED update still refused the next
    update for the full 10 minutes)."""
    if store is None:
        raise ApiError(500, "no config store")
    repo = store.data.get("repoPath")
    if not repo or not os.path.isdir(repo):
        raise ApiError(400, "no repo folder recorded at install time - run install.py from the clone")
    if not os.path.isfile(os.path.join(repo, "install.py")):
        raise ApiError(400, "no install.py in %s - update the clone" % repo)
    cfg_dir = os.path.dirname(str(store.path))
    lock = update_flag_path(store)
    now = time.time()
    try:
        with open(lock, "r", encoding="utf-8") as f:
            parts = (f.read() or "").split()
        prev = float(parts[0]) if parts else 0.0
        prev_pid = int(parts[1]) if len(parts) > 1 else 0
        if prev > 0 and installer_pid_alive(prev_pid):
            if now - prev < 600:
                raise ApiError(409, "an update is already running (started %d s ago)"
                               " - wait for the server to come back" % int(now - prev))
        # no lock, or the recorded installer is gone: stale lock - start fresh
    except ApiError:
        raise
    except Exception:
        pass   # unreadable lock - start fresh
    os.makedirs(os.path.join(cfg_dir, "logs"), exist_ok=True)
    run_log = os.path.join(cfg_dir, "logs", "update_run.log")
    flags, kwargs = 0, {}
    if os.name == "nt":
        flags = 0x00000008 | 0x00000200 | 0x08000000   # detached, no window
    else:
        kwargs["start_new_session"] = True
    cmd = [sys.executable, os.path.join(repo, "install.py"), "--update"]
    with open(run_log, "ab") as logf:
        p = subprocess.Popen(cmd, cwd=repo, stdin=subprocess.DEVNULL,
                             stdout=logf, stderr=logf,
                             creationflags=flags, **kwargs)
    dbg_line(store, "update", "installer.spawned", {"pid": p.pid, "cmd": cmd})
    try:
        with open(lock, "w", encoding="utf-8") as f:
            f.write("%.2f %d" % (time.time(), p.pid))   # 0.9.314: the pid lands IN the lock
    except OSError:
        pass
    return {"ok": True, "started": True, "pid": p.pid, "repoPath": repo,
            "what": "git pull + redeploy + restart - the server drops mid-run"
                    " and comes back on the new build",
            "logPath": run_log}


def update_check(force_latest=None, store=None):
    """Compare the running VERSION with the latest in the GitHub repo.

    Reads the VERSION file from GitHub (contents API, raw fallback; no git
    involved). Cached for 10 minutes; ?latest= overrides the remote value
    (used by tests). A private repo needs a read-only token in the env var
    OFFICEKICK_GITHUB_TOKEN or the file ~/.officekick/github_token.
    """
    now = time.time()
    if not force_latest:
        cached = UPDATE_CACHE["data"]
        if cached and now - UPDATE_CACHE["t"] < 120:
            return cached
    latest = force_latest or None
    source = "github"
    pull_available = False
    repo_info = None
    out_unusable_reason = None
    if latest is None:
        repo_info = git_update_probe(store)
        if repo_info and not repo_info.get("usable"):
            out_unusable_reason = repo_info.get("reason") or "unknown"
        if repo_info.get("usable") and repo_info.get("remoteVer"):
            latest = repo_info["remoteVer"]
            source = "git clone (%s)" % repo_info.get("repoPath", "")
            pull_available = True
    if latest is None:
        # fall back to the GitHub raw VERSION file (no local clone usable)
        headers = {"User-Agent": "officekick/" + VERSION,
                   "Accept": "application/vnd.github.raw"}
        raw_url = "https://raw.githubusercontent.com/corelan/officekick/main/VERSION"
        try:
            req = urllib.request.Request(raw_url, headers=headers)
            with urllib.request.urlopen(req, timeout=8) as r:
                latest = r.read().decode("utf-8", "replace").strip()
        except Exception as exc:
            return {"ok": False, "error": "could not check for updates: %s" % exc,
                    "current": VERSION}
    latest = (latest or "").strip()
    if not latest:
        return {"ok": False, "error": "no version published in the repo", "current": VERSION}
    up_to_date = _version_tuple(latest) <= _version_tuple(VERSION)
    data = {"ok": True, "current": VERSION, "latest": latest,
            "upToDate": up_to_date,
            "repo": "https://github.com/corelan/officekick",
            "howToUpdate": ("Click \'Update now (pull + redeploy + restart)\'"
                            " below, or run install.py --update in %s and"
                            " reload the pane."
                            % (repo_info or {}).get("repoPath", "your clone")
                            if pull_available else
                            "Run install.py --update in %s, then reload the pane."
                            % ((repo_info or {}).get("repoPath", "your clone"))),
            "source": source, "pullAvailable": pull_available,
            "probeReason": out_unusable_reason}
    if not force_latest:
        UPDATE_CACHE["t"] = now
        UPDATE_CACHE["data"] = data
    return data


