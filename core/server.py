SESSION_ID_RE = re.compile(r"^[a-f0-9-]{8,64}$")


class SessionStore:
    """Session files organized per add-in: sessions/<slidekick|wordkick|
    mailkick>/<sid>.json since 0.9.243 - one folder per app keeps manual
    cleanup/backup trivial. Legacy flat files (sessions/<sid>.json) are
    migrated on boot by their stored "app" field; files without a known app
    stay at the root as legacy/shared and remain visible everywhere, and
    reads always fall back to the root so old builds and old docs still
    resolve."""

    APPS = ("slidekick", "wordkick", "mailkick")

    def __init__(self, base_dir):
        self.dir = Path(base_dir) / "sessions"
        try:
            if os.name == "nt":
                self.dir.mkdir(parents=True, exist_ok=True)
            else:
                self.dir.mkdir(mode=0o700, parents=True, exist_ok=True)
            os.chmod(self.dir, 0o700)
        except OSError:
            pass
        for app in self.APPS:
            d = self.dir / app
            if d.is_dir():
                try:
                    if os.name != "nt":
                        os.chmod(d, 0o700)
                except OSError:
                    pass
        self._migrate_legacy()
        for f in self._all_files():
            try:
                os.chmod(f, 0o600)
            except OSError:
                pass

    def _appdir(self, app):
        """Per-app folder when the app is known, else the legacy root."""
        if app in self.APPS:
            return self.dir / app
        return self.dir

    def _all_files(self):
        out = list(self.dir.glob("*.json"))
        for app in self.APPS:
            d = self.dir / app
            if d.is_dir():
                out.extend(d.glob("*.json"))
        return out

    def _find(self, sid):
        """Path of an existing session doc: its per-app folder first (known
        via the doc), then the legacy root location."""
        cands = list(self.dir.glob(sid + ".json"))
        for app in self.APPS:
            p = self.dir / app / (sid + ".json")
            if p.is_file():
                cands.append(p)
        return cands[0] if cands else None

    def _migrate_legacy(self):
        """Move legacy flat session files into their app subfolder (idempotent;
        never breaks boot)."""
        try:
            for f in self.dir.glob("*.json"):
                try:
                    data = json.loads(f.read_text(encoding="utf-8"))
                except Exception:
                    continue
                app = data.get("app")
                if app not in self.APPS:
                    continue          # legacy/shared docs stay visible everywhere
                dst = self.dir / app
                try:
                    if os.name == "nt":
                        dst.mkdir(parents=True, exist_ok=True)
                    else:
                        dst.mkdir(mode=0o700, parents=True, exist_ok=True)
                        os.chmod(dst, 0o700)
                except OSError:
                    continue
                try:
                    f.rename(dst / f.name)
                    if os.name != "nt":
                        try:
                            os.chmod(dst / f.name, 0o600)
                        except OSError:
                            pass
                except OSError:
                    continue
        except Exception:
            pass

    def _valid(self, sid):
        return bool(SESSION_ID_RE.match(sid or ""))

    def list(self, app=None):
        items = []
        for f in self._all_files():
            try:
                data = json.loads(f.read_text(encoding="utf-8"))
                doc_app = data.get("app")
                # sessions are scoped per application; rows without an app are
                # legacy/shared and stay visible in every pane
                if app and doc_app and doc_app != app:
                    continue
                items.append({
                    "id": data.get("id", f.stem),
                    "name": data.get("name") or "session",
                    "updated": data.get("updated") or f.stat().st_mtime,
                    "messages": len(data.get("exchanges") or []),
                    "app": doc_app,
                    "manualName": bool(data.get("manualName")),
                })
            except Exception:
                continue
        items.sort(key=lambda x: x["updated"], reverse=True)
        return items

    def get(self, sid):
        if not self._valid(sid):
            raise ApiError(400, "Invalid session id")
        f = self._find(sid)
        if f is None:
            raise ApiError(404, "Unknown session: %s" % sid)
        try:
            return json.loads(f.read_text(encoding="utf-8"))
        except Exception:
            raise ApiError(500, "Session file unreadable")

    def create(self, name, exchanges, app=None):
        sid = uuid.uuid4().hex
        return self.upsert(sid, name, exchanges, app=app)

    def upsert(self, sid, name, exchanges, existing=None, app=None, manual=None):
        if not self._valid(sid):
            raise ApiError(400, "Invalid session id")
        # the stored file is the source of truth: if the caller does not
        # pass the current exchanges (or passes a shorter history), keep
        # the longer stored list instead of shrinking the session
        f = self._find(sid)
        base = existing
        if base is None and f is not None:
            try:
                base = json.loads(f.read_text(encoding="utf-8"))
            except Exception:
                base = None
        stored_ex = (base or {}).get("exchanges") or []
        new_ex = self._clean_exchanges(exchanges)
        ex = new_ex if len(new_ex) >= len(stored_ex) else stored_ex
        doc = {
            "id": sid,
            "name": (name or (base or {}).get("name") or "session")[:80],
            "updated": time.time(),
            "exchanges": ex,
            "app": app if app in ("slidekick", "wordkick", "mailkick")
                   else (base or {}).get("app"),
            # manualName = the user renamed this session themselves; AI title
            # updates stop until the refresh button is used (None = keep what
            # is stored; absent = AI-generated and auto-updates stay allowed)
            "manualName": True if manual else bool((base or {}).get("manualName")),
        }
        # organize per app (0.9.243): sessions/<slidekick|wordkick|mailkick>/
        doc_app = doc.get("app")
        d = self._appdir(doc_app)
        if d is not self.dir:
            try:
                if os.name == "nt":
                    d.mkdir(parents=True, exist_ok=True)
                else:
                    d.mkdir(mode=0o700, parents=True, exist_ok=True)
                    os.chmod(d, 0o700)
            except OSError:
                d = self.dir
        f = d / (sid + ".json")
        legacy = self.dir / (sid + ".json")
        if d is not self.dir and legacy.is_file():
            try:
                legacy.unlink()
            except OSError:
                pass
        f.write_text(json.dumps(doc, indent=1), encoding="utf-8")
        if os.name != "nt":
            os.chmod(f, 0o600)   # Windows: chmod maps to ACL quirks and can fail under task tokens
        # an app folder switch (e.g. re-registered doc) must not leave twins
        for other in self.APPS:
            of = self.dir / other / (sid + ".json")
            if other != doc_app and of.is_file():
                try:
                    of.unlink()
                except OSError:
                    pass
        return {"id": sid, "name": doc["name"], "updated": doc["updated"], "messages": len(ex)}

    def rename(self, sid, name, manual=None):
        doc = self.get(sid)
        # title-repair: the model may answer with reasoning fragments, fences,
        # labels ("Title: x") or long essays - derive a clean short title
        import re as _re
        n = str(name or "")
        n = _re.sub(r"<think>[\s\S]*?</think>", "", n, flags=_re.I)
        n = _re.sub(r"^\s*```.*?```\s*$", "", n, flags=_re.S)
        n = _re.sub(r"^\s*(title|session title|titel)\s*[:\-]\s*", "", n, flags=_re.I)
        n = n.replace('"', "").replace("`", "").strip()
        nl = [ln for ln in n.splitlines() if ln.strip()]
        n = nl[0].strip() if nl else ""
        words = n.split()
        if len(words) > 7:
            n = " ".join(words[:7])
        if not n:
            n = ""   # empty = keep the stored/derived name
        return self.upsert(sid, n[:80], doc.get("exchanges"), doc, manual=manual)

    def remove_pair(self, sid, ts):
        """Explicitly remove the exchange pair stamped `ts` (user + assistant
        share one stamp from the panes). Unlike upsert this SHRINKS the stored
        list on purpose - an intentional deletion."""
        self._valid(sid)
        f = self._find(sid)
        if f is None:
            raise ApiError(404, "Session not found: %s" % sid)
        doc = json.loads(f.read_text(encoding="utf-8"))
        ex = doc.get("exchanges") or []
        before = len(ex)
        ex2 = [e for e in ex if str(e.get("ts") or "") != str(ts)]
        if len(ex2) == before:
            raise ApiError(404, "No exchange pair matches that timestamp")
        doc["exchanges"] = ex2
        doc["updated"] = time.time()
        f.write_text(json.dumps(doc, indent=1), encoding="utf-8")
        try:
            os.chmod(f, 0o600)
        except OSError:
            pass
        return {"ok": True, "removed": before - len(ex2), "messages": len(ex2)}

    def auto_clean(self, days, now=None):
        """Delete sessions whose NEWEST exchange timestamp is older than `days`
        days. Timestamps in exchanges are ms-epoch strings from the panes;
        fall back to the session's `updated` float, then the file mtime.
        Returns the ids of the removed sessions."""
        now = now if now is not None else time.time()
        cutoff = now - max(1, int(days)) * 86400.0
        removed = []
        for f in self._all_files():
            try:
                data = json.loads(f.read_text(encoding="utf-8"))
            except Exception:
                continue
            ts_list = []
            for ex in data.get("exchanges") or []:
                try:
                    if ex and ex.get("ts"):
                        ts_list.append(float(ex["ts"]))
                except (TypeError, ValueError):
                    continue
            norm = [t / 1000.0 if t > 1e12 else t for t in ts_list]
            newest = max(norm) if norm else None
            if newest is None:
                newest = data.get("updated") or f.stat().st_mtime
            if newest < cutoff:
                try:
                    f.unlink()
                    removed.append(data.get("id") or f.stem)
                except OSError:
                    pass
        return {"count": len(removed), "removed": removed}

    def delete(self, sid):
        if not self._valid(sid):
            raise ApiError(400, "Invalid session id")
        f = self._find(sid)
        if f is None:
            raise ApiError(404, "Unknown session: %s" % sid)
        f.unlink()
        return {"ok": True}

    @staticmethod
    def _clean_exchanges(exchanges):
        """Keep role/content only, cap volume (last 40 messages)."""
        out = []
        for m in exchanges or []:
            if not isinstance(m, dict):
                continue
            role = m.get("role")
            content = m.get("content")
            if role in ("user", "assistant") and isinstance(content, str):
                entry = {"role": role, "content": content[:8000]}
                ts = str(m.get("ts") or "").strip()
                if ts:
                    entry["ts"] = ts[:32]   # when the exchange happened
                out.append(entry)
        return out[-40:]


